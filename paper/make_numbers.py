def e7() -> None:  # noqa: PLR0915
    f = R / "readout_eval_matched.json"
    if not f.exists():
        raise FileNotFoundError(2, "missing", str(f))
    res = json.loads(f.read_text())
    runs = {m: json.loads((R / f"readout_eval_matched_{m}.json").read_text())
            for m in res["models"]}
    rows = next(iter(runs.values()))["rows"]
    put("e7.npairs", len(rows))
    put("e7.npat", len({e6mod.patient(r["image"]) for r in rows}))
    put("e7.nfilms", len({r["image"] for r in rows}))
    put("e7.nsamples", res["n_samples"])
    put("e7.nboot", f"{res['n_boot']:,}".replace(",", "{,}"))
    lines, allD = [], []
    for m, r in res["models"].items():
        mk, label = E6_MODELS[m]
        d = runs[m]
        put(f"e7.{mk}.verdict", verdict(r["e7"]["verdict"]))
        put(f"e7.{mk}.e6rule", verdict(r["reported"]["e6_rule_verdict"]))
        put(f"e7.{mk}.nonesamples",
            sum(p == "NONE" for x in d["rows"] for p in x["samples_parsed"]))
        put(f"e7.{mk}.nsamplestotal", f"{d['n_samples'] * len(d['rows']):,}".replace(",", "{,}"))
        put(f"e7.{mk}.gatemax", num(max(x["first_token_diff"] for x in d["rows"]), 3))
        rep = r["reported"]["by_finding"]
        tied = [rep[g]["tied"] for g in E6_FINDINGS]
        put(f"e7.{mk}.tiedmin", f"{100 * min(tied):.0f}\\%")
        put(f"e7.{mk}.tiedmax", f"{100 * max(tied):.0f}\\%")
        masses = [rep[g]["mass_mean"] for g in E6_FINDINGS]
        put(f"e7.{mk}.massmin", num(min(masses)))
        put(f"e7.{mk}.massmax", num(max(masses)))
        ds = [r["e7"]["by_finding"][g][k]["D"] for g in E6_FINDINGS for k in ("raw", "norm")]
        put(f"e7.{mk}.maxhw", num(max((hi - lo) / 2 for _, lo, hi in ds), 3))
        put(f"e7.{mk}.maxbound", num(max(max(-lo, hi) for _, lo, hi in ds), 2))
        if not all(lo <= 0 <= hi for _, lo, hi in ds):
            warnings.append(f"E7 {m}: some interval of D excludes 0; prose says none does")
        gaps = [rep[g]["e6_rule_diff"][f"{k}-s"][0] for g in E6_FINDINGS for k in ("raw", "norm")]
        put(f"e7.{mk}.gapmin", num(min(gaps), 3))
        put(f"e7.{mk}.gapmax", num(max(gaps), 3))
        # After the run, not pre-registered: the share of films whose yes count lies outside the
        # central 95% of Binomial(n, P), the planning simulation's assumption, per finding/readout.
        n = d["n_samples"]
        out = []
        for g in E6_FINDINGS:
            rs = [x for x in d["rows"] if x["finding"] == g]
            k = np.array([sum(p == "YES" for p in x["samples_parsed"]) for x in rs])
            for key in ("raw", "norm"):
                pr = np.array([x[key] for x in rs])
                out.append(np.mean((k < binom.ppf(0.025, n, pr)) | (k > binom.ppf(0.975, n, pr))))
        put(f"e7.{mk}.outbinmin", f"{100 * min(out):.0f}\\%")
        put(f"e7.{mk}.outbinmax", f"{100 * max(out):.0f}\\%")
        lines.append(f"\\multicolumn{{7}}{{l}}{{\\emph{{{label}}}}} \\\\")
        for g, fk in E6_FINDINGS.items():
            v, t = r["e7"]["by_finding"][g], rep[g]
            put(f"e7.{mk}.{fk}.npos", v["n_pos"])
            put(f"e7.{mk}.{fk}.nneg", v["n_neg"])
            put(f"e7.{mk}.{fk}.auc.s", num(v["auc_s"], 3))
            put(f"e7.{mk}.{fk}.s0n", t["s0_n"])
            put(f"e7.{mk}.{fk}.s0pos", t["s0_pos"])
            if t["s0_auc_raw"] is not None:
                put(f"e7.{mk}.{fk}.s0auc", num(t["s0_auc_raw"]))
            for k in ("raw", "norm"):
                put(f"e7.{mk}.{fk}.auc.{k}", num(v[k]["auc_P"], 3))
                put(f"e7.{mk}.{fk}.eauc.{k}", num(v[k]["eauc_q"], 3))
                put(f"e7.{mk}.{fk}.D.{k}", ci(v[k]["D"], 3, sign=True))
                pt, lo, hi = t["e6_rule_diff"][f"{k}-s"]  # stored readout minus s; shown s minus
                put(f"e7.{mk}.{fk}.unmatched.{k}", ci((-pt, -hi, -lo), 3, sign=True))
                allD.append(v[k]["D"])
            fmt = "${:+.3f}$ {{\\scriptsize$[{:+.3f},\\,{:+.3f}]$}}"
            cells = [f"{v['raw']['auc_P']:.3f}", f"{v['norm']['auc_P']:.3f}", f"{v['auc_s']:.3f}",
                     fmt.format(-t["e6_rule_diff"]["raw-s"][0], -t["e6_rule_diff"]["raw-s"][2],
                                -t["e6_rule_diff"]["raw-s"][1]),
                     fmt.format(*v["raw"]["D"]), fmt.format(*v["norm"]["D"])]
            lines.append(f"{g.capitalize()} & " + " & ".join(cells) + " \\\\")
        lines.append("\\midrule")
    ns = {v[k] for r in res["models"].values() for v in r["e7"]["by_finding"].values()
          for k in ("n_pos", "n_neg")}
    if len(ns) != 1:
        warnings.append(f"E7: unequal class sizes {sorted(ns)}; prose says one size")
    put("e7.nper", min(ns))
    put("e7.maxabsD", num(max(abs(x[0]) for x in allD), 3))
    put("e7.maxhw", num(max((x[2] - x[1]) / 2 for x in allD), 3))
    table("e7", "\\begin{tabular}{lcccccc}\n\\toprule\n"
          "& \\multicolumn{3}{c}{AUC} & \\multicolumn{3}{c}{AUC of $s$ minus} \\\\\n"
          "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n"
          "Finding & $\\Praw$ & $\\Pnorm$ & $s$ & AUC of $\\Praw$ "
          "& $\\mathbb{E}\\,$AUC of $q_{\\text{raw}}$ "
          "& $\\mathbb{E}\\,$AUC of $q_{\\text{norm}}$ \\\\\n"
          "\\midrule\n" + "\n".join(lines[:-1]) + "\n\\bottomrule\n\\end{tabular}")
    for g, fk in E6_FINDINGS.items():
        for k, v in res["across"]["by_finding"][g].items():
            put(f"e7.rank.{fk}.{k}", ci(v, 3, sign=True))
    acr = [v for g in E6_FINDINGS for v in res["across"]["by_finding"][g].values()]
    if not (all(hi < 0 for _, _, hi in acr) or all(lo > 0 for _, lo, _ in acr)):
        warnings.append("E7 across: the scores do not all separate the models the same way")


