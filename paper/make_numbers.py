# E6: the stratified evaluation, scored four ways, in each model
# --------------------------------------------------------------------------------------------
E6_MODELS = {"medgemma": ("mg", "MedGemma 1.5 4B"), "lingshu": ("ls", "Lingshu-7B"),
             "chexagent": ("cx", "CheXagent-2 3B")}
E6_FINDINGS = {"cardiomegaly": "card", "effusion": "eff", "pneumothorax": "ptx"}


def e6() -> None:
    runs = {}
    for m in E6_MODELS:
        f = R / f"readout_eval_answers_{m}.json"
        if f.exists():
            runs[m] = json.loads(f.read_text())
    if "medgemma" not in runs:
        raise FileNotFoundError(2, "missing", str(R / "readout_eval_answers_medgemma.json"))
    rf = R / "readout_eval_resolution.json"
    resol = json.loads(rf.read_text()) if rf.exists() else None
    if resol is None:
        warnings.append("E6: missing readout_eval_resolution.json (matched-resolution column)")
    lines = []
    for m, d in runs.items():
        mk, label = E6_MODELS[m]
        rm = resol["models"].get(m) if resol else None
        put(f"e6.{mk}.nonesamples",
            sum(p == "NONE" for r in d["rows"] for p in r["samples_parsed"]))
        put(f"e6.{mk}.nsamplestotal", f"{d['n_samples'] * len(d['rows']):,}".replace(",", "{,}"))
        masses = [d["by_finding"][f]["mass_mean"] for f in E6_FINDINGS if f in d["by_finding"]]
        put(f"e6.{mk}.massmin", num(min(masses)))
        put(f"e6.{mk}.massmax", num(max(masses)))
        if rm:
            tied = [rm[f]["tied"] for f in E6_FINDINGS]
            put(f"e6.{mk}.tiedmin", f"{100 * min(tied):.0f}\\%")
            put(f"e6.{mk}.tiedmax", f"{100 * max(tied):.0f}\\%")
            for f, fk in E6_FINDINGS.items():
                put(f"e6.{mk}.{fk}.s0n", rm[f]["s0_n"])
                put(f"e6.{mk}.{fk}.s0pos", rm[f]["s0_pos"])
                if rm[f]["s0_auc_raw"] is not None:
                    put(f"e6.{mk}.{fk}.s0auc", num(rm[f]["s0_auc_raw"]))
                for k in ("raw", "norm"):  # stored as AUC(s) - AUC(q); shown as q minus s
                    pt, lo, hi = rm[f][f"s-q{k}"]
                    put(f"e6.{mk}.{fk}.matched.{k}", ci((-pt, -hi, -lo), 3, sign=True))
        if "verdict" in d:
            res = {"by_finding": d["by_finding"], "verdict": d["verdict"]}
        else:
            warnings.append(f"E6 {m} is partial ({len(d['rows'])} film-finding pairs, no verdict)")
            res = e6mod.analyze(d["rows"])
        put(f"e6.{mk}.verdict", verdict(res["verdict"]))
        put(f"e6.{mk}.nsamples", d.get("n_samples", 20))
        put(f"e6.{mk}.nlevels", d.get("n_samples", 20) + 1)
        if m == "medgemma":
            put("e6.npairs", len(d["rows"]))
        lines.append(f"\\multicolumn{{7}}{{l}}{{\\emph{{{label}}}}} \\\\")
        for f, fk in E6_FINDINGS.items():
            if f not in res["by_finding"]:
                continue
            r = res["by_finding"][f]
            put(f"e6.{mk}.{fk}.npos", r["n_pos"])
            put(f"e6.{mk}.{fk}.nneg", r["n_neg"])
            put(f"e6.{mk}.{fk}.mass", num(r["mass_mean"]))
            put(f"e6.{mk}.{fk}.greedynone", r["greedy_none"])
            for k in e6mod.SCORES:
                lo, hi = r["ci"][k]
                put(f"e6.{mk}.{fk}.auc.{k}", ci((r["auc"][k], lo, hi), 3))
                put(f"e6.{mk}.{fk}.acc.{k}", num(r["accuracy"][k]))
            for k in ("raw", "norm"):
                put(f"e6.{mk}.{fk}.{k}vs", ci(r["diff"][f"{k}-s"], 3, sign=True))
                put(f"e6.{mk}.{fk}.dis.{k}", r["calls_disagree_with_sampled"][k])
            cells = [f"{r['auc'][k]:.3f}" for k in e6mod.SCORES]
            fmt = "${:+.3f}$ {{\\scriptsize$[{:+.3f},\\,{:+.3f}]$}}"
            cells += [fmt.format(*r["diff"][f"{k}-s"]) for k in ("raw", "norm")]
            lines.append(f"{f.capitalize()} ({r['n_pos']}/{r['n_neg']}) & "
                         + " & ".join(cells) + " \\\\")
        lines.append("\\midrule")
    table("e6", "\\begin{tabular}{lcccccc}\n\\toprule\n"
          "& \\multicolumn{4}{c}{AUC} & \\multicolumn{2}{c}{AUC minus AUC of $s$} \\\\\n"
          "\\cmidrule(lr){2-5}\\cmidrule(lr){6-7}\n"
          "Finding (pos/neg) & $\\Praw$ & $\\Pnorm$ & $s$ & greedy & $\\Praw$ & $\\Pnorm$ "
          "\\\\\n\\midrule\n" + "\n".join(lines[:-1])
          + "\n\\bottomrule\n\\end{tabular}")
    if resol:
        allm = [rm[f][f"s-q{k}"] for rm in resol["models"].values() for f in E6_FINDINGS
                for k in ("raw", "norm")]
        put("e6.res.maxabs", num(max(abs(x[0]) for x in allm), 2))
        if not all(lo <= 0 <= hi for _, lo, hi in allm):
            warnings.append("E6 matched resolution: some interval excludes 0; prose says none does")
        for f, fk in E6_FINDINGS.items():
            v = resol["across"]["by_finding"][f]["qraw"]
            put(f"e6.res.rank.{fk}", ci(v, 3, sign=True))
        if not all(resol["across"]["by_finding"][f]["qraw"][2] < 0 for f in E6_FINDINGS):
            warnings.append("E6 matched resolution: a model comparison does not separate")
    others = [m for m in runs if m != "medgemma"]
    if others:
        c = e6mod.compare(runs["medgemma"], runs[others[0]])
        put("e6.rank.model", E6_MODELS[others[0]][1])
        put("e6.rank.verdict", verdict(c["verdict"]))
        for f, fk in E6_FINDINGS.items():
            if f in c["by_finding"]:
                for k in e6mod.SCORES:
                    put(f"e6.rank.{fk}.{k}", ci(c["by_finding"][f]["auc_diff"][k], 3, sign=True))


