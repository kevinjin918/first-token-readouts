# Hand reading of the parse rule, and E4's verdicts with every NONE recoded (not pre-registered)
# --------------------------------------------------------------------------------------------
def hand() -> None:
    h = json.loads((R / "hand_reading_scored.json").read_text())
    put("hand.e4.n", h["e4"]["read"])
    put("hand.e4.agree", h["e4"]["agree"])
    put("hand.e2.n", h["e2"]["outputs_read"])
    put("hand.e2.agree", h["e2"]["outputs_agree"])
    put("hand.e2.distinct", h["e2"]["read"])
    put("hand.e2.distinctagree", h["e2"]["agree"])
    rows = json.loads((R / "readout_sampled_answers.json").read_text())["rows"]
    for to in ("YES", "NO"):
        def rec(p: str, to: str = to) -> str:
            return to if p == "NONE" else p
        recoded = [{**r, "arms": {a: {**v, "greedy_parsed": rec(v["greedy_parsed"]),
                                      "samples_parsed": [rec(p) for p in v["samples_parsed"]]}
                                  for a, v in r["arms"].items()}} for r in rows]
        v = analyze(recoded)["verdicts"]
        for k in ("V1_norm_s", "V1_raw_s", "V2", "V3_s"):
            put(f"sens.{to.lower()}.{k.replace('_', '')}", verdict(v[k]))


# --------------------------------------------------------------------------------------------
# Occlusion: where the evidence sits; effusion check
# --------------------------------------------------------------------------------------------
def occlusion() -> None:
    rows = json.loads((R / "occlusion_readout_audit.json").read_text())["rows"]
    rc = [divmod(r["top_block"], NB) for r in rows]
    put("loc.n", len(rows))
    put("loc.central", sum(2 <= i <= 5 and 2 <= j <= 5 for i, j in rc))
    put("loc.leftheart", sum(j in (4, 5) for _, j in rc))
    eff = [r for r in rows if r["effusion_base"]["norm"] >= 0.5]
    put("occ.eff.n", len(eff))
    put("occ.eff.minnorm", num(min(r["effusion_occ"]["norm"] for r in eff), 3))


