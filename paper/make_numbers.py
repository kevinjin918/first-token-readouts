# --------------------------------------------------------------------------------------------
# formatting
# --------------------------------------------------------------------------------------------
def num(x: float, d: int = 2, sign: bool = False) -> str:
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return "\\ensuremath{" + s + "}"


def ci(t: tuple | list, d: int = 2, sign: bool = False) -> str:
    m, lo, hi = t
    f = (lambda v: f"{v:+.{d}f}") if sign else (lambda v: f"{v:.{d}f}")
    return f"\\ensuremath{{{f(m)}\\;[{f(lo)},\\,{f(hi)}]}}"


def verdict(v: str) -> str:
    return "\\textsc{" + v.lower() + "}"


def tex_escape(s: str) -> str:
    rep = {"\\": "\\textbackslash{}", "{": "\\{", "}": "\\}", "#": "\\#", "$": "\\$", "%": "\\%",
           "&": "\\&", "_": "\\_", "^": "\\^{}", "~": "\\~{}"}
    return "".join(rep.get(c, c) for c in s)


def put(key: str, value: object) -> None:
    if key in vals:
        raise KeyError(f"{key} written twice")
    vals[key] = str(value)


def table(name: str, text: str) -> None:
    (OUT / "tables").mkdir(exist_ok=True)
    (OUT / "tables" / f"{name}.tex").write_text(
        f"% generated by paper/make_numbers.py; do not edit\n{text}\n")


