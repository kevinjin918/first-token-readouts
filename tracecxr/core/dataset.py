"""The dataset contract and the bundled synthetic fixture loader.

:class:`FixtureDataset` loads the tiny, deterministic CXR fixture shipped in
``tracecxr/fixtures/``. It needs no downloads and exists so every unit can run end-to-end
against realistic-shaped records in CI.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Protocol, runtime_checkable

import numpy as np

from tracecxr.core.types import BBox, CXRRecord, Finding, Label

FIXTURES_DIR = Path(__file__).resolve().parent.parent / "fixtures"


@runtime_checkable
class Dataset(Protocol):
    """An iterable source of :class:`CXRRecord`."""

    name: str

    def __iter__(self) -> Iterator[CXRRecord]:
        ...

    def __len__(self) -> int:
        ...


class FixtureDataset:
    """The bundled synthetic fixture: a handful of records covering the focus findings.

    Reads ``fixtures/manifest.json`` (annotations) and the per-record ``.npy`` images. The
    fixture is generated by ``fixtures/generate.py`` and committed, so loading is offline.
    """

    name = "fixture"

    def __init__(self, root: Path | None = None) -> None:
        self.root = Path(root) if root is not None else FIXTURES_DIR
        manifest_path = self.root / "manifest.json"
        if not manifest_path.exists():
            raise FileNotFoundError(
                f"fixture manifest not found at {manifest_path}; "
                "run `python -m tracecxr.fixtures.generate` to create it"
            )
        self._manifest = json.loads(manifest_path.read_text())

    def __len__(self) -> int:
        return len(self._manifest["records"])

    def __iter__(self) -> Iterator[CXRRecord]:
        for entry in self._manifest["records"]:
            image = np.load(self.root / entry["image"])
            findings = {Finding(k): Label(v) for k, v in entry.get("findings", {}).items()}
            bboxes = {
                Finding(k): [BBox(**b) for b in boxes]
                for k, boxes in entry.get("bboxes", {}).items()
            }
            yield CXRRecord(
                id=entry["id"],
                image=image,
                report=entry.get("report"),
                findings=findings,
                bboxes=bboxes,
                source="fixture",
                metadata=entry.get("metadata", {}),
            )

    def records(self) -> list[CXRRecord]:
        return list(self)


def load_dataset(name: str) -> Iterable[CXRRecord]:
    """Resolve a dataset by name. Only ``"fixture"`` is available without extra data on disk.

    Real loaders (chestxray14, vindr, chexpert_plus) register themselves when imported and
    extend this resolver via :data:`_DATASETS`.
    """
    if name in _DATASETS:
        return _DATASETS[name]()
    raise KeyError(f"unknown dataset {name!r}; registered: {sorted(_DATASETS)}")


_DATASETS: dict[str, type[Dataset] | callable] = {"fixture": FixtureDataset}


def register_dataset(name: str, factory: object) -> None:
    """Register a dataset factory (real loaders call this on import)."""
    _DATASETS[name] = factory  # type: ignore[assignment]


def available_datasets() -> list[str]:
    return sorted(_DATASETS)


def materialize_image(record: CXRRecord) -> np.ndarray | None:
    """Return ``record.image``, lazily loading it from ``metadata['image_path']`` if absent.

    Dataset loaders default to lazy images (``image=None``, path in metadata) so building a
    100k-record dataset stays cheap. Metrics and adapters that need pixels call this to
    materialize on demand — only the records actually evaluated pay the decode cost. Returns
    ``None`` when neither an in-memory image nor a readable path is available.
    """
    if record.image is not None:
        return record.image
    path = record.metadata.get("image_path")
    if not path or not Path(path).exists():
        return None
    from PIL import Image  # lazy: pillow is a base dep but keep import local to the I/O path

    return np.asarray(Image.open(path).convert("L"))
