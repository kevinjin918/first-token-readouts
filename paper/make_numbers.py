# E5: contrastive and anchored feature sets
# --------------------------------------------------------------------------------------------
E5_GROUPS = {"fp": "fp", "tp_cardiomegaly": "tpcard", "tp_effusion": "tpeff"}
E5_ARMS = {"top": ("top", "Own top $80$ (the paper's)"),
           "con_card": ("concard", "Cardiomegaly contrast"),
           "con_eff": ("coneff", "Effusion contrast"),
           "rand_act": ("rand", "Random active $80$"),
           "anch_evid": ("evid", "Anchored, evidence block"),
           "anch_border": ("border", "Anchored, border block")}


def e5() -> None:
    d = json.loads((R / "clamp_contrastive_answers.json").read_text())
    if "verdicts" in d:
        res = {"summary": d["summary"], "verdicts": d["verdicts"]}
    else:
        n_test = 80  # E4's fp (40) + tp_cardiomegaly (20) + tp_effusion (20)
        warnings.append(f"E5 has no saved verdicts ({len(d['rows'])} of {n_test} films)")
        res = e5mod.analyze(d["rows"], n_boot=2000)
    put("e5.ndonor", min(len(v) for v in d["donors"].values()))
    put("e5.jaccon", num(d["jaccard_con"], 3))
    put("e5.nsamples", d.get("n_samples", 30))
    S = res["summary"]
    for g, gk in E5_GROUPS.items():
        if g not in S:
            continue
        put(f"e5.{gk}.n", S[g]["top"]["n"])
        put(f"e5.{gk}.base.s", num(np.mean([e5mod.yes_rate(r["arms"]["base"]["samples_parsed"])
                                            for r in d["rows"] if r["group"] == g])))
        put(f"e5.{gk}.base.raw", num(np.mean([r["arms"]["base"]["raw"]
                                              for r in d["rows"] if r["group"] == g])))
        for arm, (ak, _) in E5_ARMS.items():
            a = S[g][arm]
            put(f"e5.{gk}.{ak}.sdrop", ci(a["s_drop"]))
            put(f"e5.{gk}.{ak}.nactive", num(a["n_active"], 1))
            put(f"e5.{gk}.{ak}.overlap", num(a["overlap_top"], 1))
            put(f"e5.{gk}.{ak}.normv", verdict(a["norm_verdict"][0] if isinstance(
                a["norm_verdict"], list) else a["norm_verdict"]))
            put(f"e5.{gk}.{ak}.rawv", verdict(a["raw_verdict"][0] if isinstance(
                a["raw_verdict"], list) else a["raw_verdict"]))
            put(f"e5.{gk}.{ak}.raw", num(a["raw"]))
    V = res["verdicts"]
    for k, key in (("S1", "S1"), ("S2", "S2"), ("S3", "S3"),
                   ("S3_tp_cardiomegaly", "S3.tpcard"), ("S3_tp_effusion", "S3.tpeff")):
        if k in V:
            put(f"e5.{key}", verdict(V[k]))
        if f"{k}_ci" in V:
            put(f"e5.{key}.ci", ci(V[f"{k}_ci"], sign=True))
    if "S1_detail" in V:
        for k, key in (("a", "a"), ("b", "b"), ("con_card_minus_rand", "cardrand"),
                       ("con_eff_minus_rand", "effrand")):
            put(f"e5.S1.{key}", ci(V["S1_detail"][k], sign=True))
    cols = [g for g in E5_GROUPS if g in S]
    head = {"fp": "False positives", "tp_cardiomegaly": "Cardiomegaly, correct",
            "tp_effusion": "Effusion, correct"}
    lines = []
    for arm, (_, label) in E5_ARMS.items():
        cells = []
        for g in cols:
            m, lo, hi = S[g][arm]["s_drop"]
            cells.append(f"${m:+.2f}$ {{\\scriptsize$[{lo:+.2f},\\,{hi:+.2f}]$}}")
        a = S["fp"][arm] if "fp" in S else S[cols[0]][arm]
        lines.append(f"{label} & ${a['n_active']:.0f}$ & ${a['overlap_top']:.0f}$ & "
                     + " & ".join(cells) + " \\\\")
    head = {"fp": "false positives", "tp_cardiomegaly": "cardiomegaly", "tp_effusion": "effusion"}
    ntp = sum(g != "fp" for g in cols)
    top = ("& & & " + ("& " if "fp" in cols else "")
           + (f"\\multicolumn{{{ntp}}}{{c}}{{correct calls}}" if ntp else "") + " \\\\\n")
    table("e5", "\\begin{tabular}{lcc" + "c" * len(cols) + "}\n\\toprule\n"
          "& & & \\multicolumn{" + str(len(cols)) + "}{c}{drop in $s$} \\\\\n"
          "\\cmidrule(lr){4-" + str(3 + len(cols)) + "}\n" + top
          + "Feature set & active & in top $80$ & " + " & ".join(head[g] for g in cols)
          + " \\\\\n\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}")


