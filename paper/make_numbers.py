    put("e2.nsamples", d["n_samples"])
    put("e2.torch", d["versions"]["torch"].split("+")[0])
    put("e2.transformers", d["versions"]["transformers"])
    for arm, (k, _) in ARMS.items():
        a = S[arm]
        put(f"e2.{k}.banked", num(a["banked_raw_maxdiff"], 3))
        put(f"e2.{k}.greedyno", a["greedy"]["NO"])
        put(f"e2.{k}.s", num(a["sampled_yes_rate"], 2))
        if arm in CLAMP_OPS:
            put(f"e2.{k}.v", verdict(a["verdict"]))
    put("e2.greedy.total", d["n"] * len(ARMS))


