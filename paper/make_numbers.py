PROMPTS = {"plain": "plain", "noformat": "no_format", "persona": "persona", "gloss": "gloss"}
CELLS = {"apfp": "card_neg_AP", "fp": "cardiomegaly_neg", "tpcard": "cardiomegaly_pos",
         "tpptx": "pneumothorax", "tpeff": "effusion"}


def load(path: Path) -> dict:
    return json.loads(path.read_text())


def prompts() -> None:
    d = load(R / "readout_prompt_confound.json")
    s = d["summary"]
    put("ps.n", d["n"])
    for k, src in PROMPTS.items():
        for q in ("raw", "norm", "mass"):
            put(f"ps.{k}.{q}", num(s[src][q], 3))
        if k != "plain":
            for q in ("raw", "norm"):
                put(f"ps.{k}.d{q}", num(s[src][q] - s["plain"][q], 3, sign=True))


def attention() -> None:
    rho, shuf = {}, {}
    for k, f in CELLS.items():
        d = load(R / f"causal_map_{f}.json")
        # the top-level rho is NaN where a film's map is constant; average over the films
        rho[k] = np.nanmean([r["rho"] for r in d["records"]])
        shuf[k] = np.nanmean([r["rho_shuffled"] for r in d["records"]])
        put(f"attn.{k}.n", d["n"])
        put(f"attn.{k}.best", num(d["best_block_mean"], 3))
        put(f"attn.{k}.nrem", d["n_removable"])
        put(f"attn.{k}.rho", num(rho[k], 3, sign=True))
        put(f"attn.{k}.shuf", num(shuf[k], 3, sign=True))
    put("attn.rhomin", num(min(rho.values()), 3, sign=True))
    put("attn.rhomax", num(max(rho.values()), 3, sign=True))
    put("attn.shufmin", num(min(shuf.values()), 3, sign=True))
    put("attn.shufmax", num(max(shuf.values()), 3, sign=True))
    put("attn.eff.bestmax", num(load(R / "causal_map_effusion.json")["best_block_max"], 3))
    put("attn.ptx.bestmax", num(load(R / "causal_map_pneumothorax.json")["best_block_max"], 3))
    pp = load(R / "attn_causal_map.json")["A"]
    put("attn.perpatch", num(pp["mean_rho"], 3, sign=True))
    # film-bootstrap interval on the per-patch mean, computed here because the run did not save one
