"""Every result number in main.tex, computed from the result files.

Writes ``paper/numbers.tex`` (``\\defval{key}{value}`` lines, read by ``\\val{key}`` in
main.tex) and the result tables under ``paper/tables/``. main.tex types no result by hand: change a
result file, rerun this, rebuild, and the PDF follows. A key the tex asks for that this script did
not write prints as a red ``??key`` and a LaTeX warning, which ``camera.sh`` turns into a failure,
as it does the warning written when a run is still partial.

Sources (results/clt_scale/):
  readout_sampled_answers.json      E4, the replication with sampled answers (main text)
  readout_generation_check.json     E2, the first generation check (rules appendix, reproduction)
  occlusion_readout_audit.json      the evidence blocks of the first 20 films (location, effusion)
  donor_sets_patient_disjoint.json  E3, patient-disjoint donor sets (selection section)
  clamp_contrastive_answers.json    E5, contrastive and anchored feature sets (selection section)
  readout_eval_answers_<model>.json E6, the stratified evaluation, one file per model (appendix)
  readout_eval_matched.json         E7, the corrected test (scope); runs: ..._matched_<model>.json
  clamp_live_mlp.json               E8, the suppression added to the live MLPs
  clamp_live_dose.json              E9, weaker live suppression at a matched answer change
  answer_text_checks.json           post-hoc checks of E4's answers: other parse rules, text
                                    degeneration, ceiling (scripts/answer_text_checks.py)
  logs/<run>.log                    the generation runs' logs (compute times)

Run from the repo root: .venv/bin/python paper/make_numbers.py
"""
