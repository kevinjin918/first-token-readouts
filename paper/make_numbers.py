# Compute: wall-clock time of each generation run, from the last progress line of its log
# --------------------------------------------------------------------------------------------
LOGS = {"e2": "readout_generation_check", "e4": "readout_sampled_answers",
        "e5": "clamp_contrastive_answers", "e6mg": "readout_eval_answers_medgemma",
        "e6cx": "readout_eval_answers_chexagent", "e7mg": "readout_eval_matched_medgemma",
        "e7cx": "readout_eval_matched_chexagent"}


def compute() -> None:
    for key, name in LOGS.items():
        f = R / "logs" / f"{name}.log"
        if not f.exists():
            raise FileNotFoundError(2, "missing", str(f))
        done = [m for m in re.finditer(r"\[(\d+)/(\d+) (\d+)s\]", f.read_text())
                if m.group(1) == m.group(2)]
        if not done:
            raise ValueError(f"{f.name}: no completed progress line")
        put(f"compute.{key}", round(int(done[-1].group(3)) / 60))


TABLES = {"e3": ("amplify", "jaccard"), "e4": ("main", "v1", "routes", "tp"), "e5": ("e5",),
          "e6": ("e6",), "e7": ("e7",)}


def main() -> None:
    for step in (e2, hand, occlusion, e3, e4, e5, e6, e7, checks, e8, e9, prompts, attention,
                 dictionary, extras, compute):
        try:
            step()
        except FileNotFoundError as e:
            warnings.append(f"{step.__name__}: missing {Path(e.filename).name}")
            for name in TABLES.get(step.__name__, ()):  # never leave a stale table in place
                table(name, f"\\todo{{table {name}: {tex_escape(Path(e.filename).name)} missing}}")
    head = ["% generated by paper/make_numbers.py; do not edit"]
    head += [f"\\PackageWarning{{numbers}}{{{w}}}" for w in warnings]
    body = [f"\\defval{{{k}}}{{{v}}}" for k, v in sorted(vals.items())]
    (OUT / "numbers.tex").write_text("\n".join(head + body) + "\n")
    print(f"wrote paper/numbers.tex ({len(vals)} values) and paper/tables/")
    for w in warnings:
        print("WARNING", w)


if __name__ == "__main__":
    main()
