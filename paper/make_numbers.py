def clt_layers() -> int:
    """Layers of the CLT, from its recorded allocation: W_enc plus span+1 decoder blocks per layer."""
    c = load(R / "clt_scale_result.json")
    return c["params"] // (c["n_features"] * c["d_model"] * (c["span"] + 2))


def dictionary() -> None:
    c = load(R / "clt_scale_result.json")
    put("clt.params", f"{c['params'] / 1e9:.2f}")
    # 'params' counts every allocated decoder block; a source layer l has no block for offsets past
    # the last layer, so those rows are never used or trained
    n_lay, block = clt_layers(), c["n_features"] * c["d_model"]
    used = (n_lay + sum(n_lay - o for o in range(c["span"] + 1))) * block
    put("clt.used", f"{used / 1e9:.2f}")
    put("clt.unused", f"{(c['params'] - used) / 1e9:.2f}")
    put("clt.span0.params", f"{load(R / 'clt_span0_result.json')['params'] / 1e9:.2f}")
    a1 = load(ROOT / "results/a1_fidelity.json")
