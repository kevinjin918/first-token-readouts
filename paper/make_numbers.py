def checks() -> None:
    c = json.loads((R / "answer_text_checks.json").read_text())
    arms = list(CLAMP_OPS)
    norm = [c["parse"][rule][f"{a}.norm"] for rule in ("last", "mention", "strict") for a in arms]
    if any(v["verdict"] != "MISREADS" or v["diff"][0] >= 0 for v in norm):
        warnings.append("post-hoc parse rules: some P_norm verdict is not MISREADS; prose says all")
    put("alt.norm.min", num(min(-v["diff"][0] for v in norm), 2))
    put("alt.norm.max", num(max(-v["diff"][0] for v in norm), 2))
    put("alt.last.changed", f"{c['parse']['last']['changed']:,}".replace(",", "{,}"))
    put("alt.nsamples", f"{4 * 50 * c['n_films']:,}".replace(",", "{,}"))
    tx = c["text"]
    pct = lambda x: f"{100 * x:.1f}\\%"  # noqa: E731
    put("text.base.trunc", pct(tx["base"]["truncated"]))
    put("text.scale1.trunc", pct(tx["clamp_scale-1"]["truncated"]))
    put("text.scale2.trunc", pct(tx["clamp_scale-2"]["truncated"]))
    put("text.clamp.noimgmax", pct(max(tx[a]["no_image"] for a in arms)))
    put("text.clamp.formatmax", pct(max(tx[a]["mentions_format"] for a in arms)))
    ce = [c["ceiling"][a] for a in arms]
    put("ceil.rhomin", num(min(x["spearman"] for x in ce), 2))
    put("ceil.rhomax", num(max(x["spearman"] for x in ce), 2))
    put("ceil.tinymin", min(x["n_tiny"] for x in ce))
    put("ceil.tinymax", max(x["n_tiny"] for x in ce))
    put("ceil.sdroptinymin", num(min(x["sdrop_tiny"] for x in ce), 2))
    put("ceil.sdroptinymax", num(max(x["sdrop_tiny"] for x in ce), 2))
    put("ceil.lowmin", num(min(-x["diff_low_margin"][0] for x in ce), 2))
    put("ceil.lowmax", num(max(-x["diff_low_margin"][0] for x in ce), 2))
    put("ceil.highmin", num(min(-x["diff_high_margin"][0] for x in ce), 2))
    put("ceil.highmax", num(max(-x["diff_high_margin"][0] for x in ce), 2))
    if not all(x["diff_low_margin"][0] < x["diff_high_margin"][0] for x in ce):
        warnings.append("ceiling: shortfall not larger on the low-margin half in every arm")


