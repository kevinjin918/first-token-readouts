def routes(recs: list[dict]) -> dict[str, float]:
    """Pooled over films and samples: share answering directly / reasoning first, and outcomes."""
    direct = [(w, p) for a in recs for w, p in zip(a["samples_open"], a["samples_parsed"],
                                                    strict=True) if w in ("yes", "no")]
    reasoned = [p for a in recs for w, p in zip(a["samples_open"], a["samples_parsed"],
                                                 strict=True) if w not in ("yes", "no")]
    n = len(direct) + len(reasoned)
    c = Counter(reasoned)
    nr = max(len(reasoned), 1)
    return {"direct": len(direct) / n, "direct_yes": np.mean([p == "YES" for _, p in direct]),
            "reasoned": len(reasoned) / n, "r_yes": c["YES"] / nr, "r_no": c["NO"] / nr,
            "r_none": c["NONE"] / nr}


def missed(recs: list[dict]) -> list[dict]:
    """Films whose greedy answer is no while P_norm still calls yes."""
    return [x for x in recs if x["greedy_parsed"] == "NO" and call(x["norm"]) == "YES"]


def e4() -> None:  # noqa: PLR0915
    d = json.loads((R / "readout_sampled_answers.json").read_text())
    rows = d["rows"]
    n_draw = sum(len(v) for v in d["draw"].values())
    if "summary" in d and len(rows) == n_draw:
        res = {"summary": d["summary"], "verdicts": d["verdicts"]}
    else:
        warnings.append(f"E4 is partial ({len(rows)} of {n_draw} films)")
        res = analyze(rows, n_boot=2000)
    S, V = res["summary"], res["verdicts"]
    fp_rows = [r for r in rows if r["group"].startswith("fp_")]
    fp = S["fp"]

    put("e4.nsamples", d.get("n_samples", 50))
    put("e4.maxtok", d.get("max_new_tokens", 128))
    put("n.fp", fp["base"]["n"])
    put("n.fppatients", len({e6mod.patient(r["image"]) for r in fp_rows}))
    for g in ("fp_banked", "fp_fresh", *TP):
        put(f"n.{g.replace('_', '')}", len(d["draw"].get(g, [])))
    put("n.tp", sum(len(d["draw"].get(g, [])) for g in TP))
    scanned = Counter(k.split("/")[0] for k in d.get("greedy_draw", {}))
    for g in ("fp_fresh", *TP):
        put(f"scanned.{g.replace('_', '')}", scanned.get(g, 0))
    put("firsttok.maxdiff", num(max(a["first_token_diff"] for r in rows
                                    for a in r["arms"].values()), 3))
    gaps0 = [r["arms"]["base"]["gap"] for r in fp_rows]
    put("fp.base.gapmedian", num(float(np.median(gaps0)), 1))
    # odds of "yes" over "no" at the median margin, two significant figures
    odds = float(np.exp(np.median(gaps0)))
    put("fp.base.gapodds", f"{float(f'{odds:.2g}'):,.0f}".replace(",", "{,}"))

    for arm, (k, _) in ARMS.items():
        a = fp[arm]
        recs = [r["arms"][arm] for r in fp_rows]
        put(f"fp.{k}.raw", num(a["raw"], 3))
        put(f"fp.{k}.raw2", num(a["raw"], 2))
        put(f"fp.{k}.norm", num(a["norm"], 3))
        put(f"fp.{k}.mass", num(a["mass"], 2))
        put(f"fp.{k}.pno", num(a["mass"] - a["raw"], 3))
        put(f"fp.{k}.s", num(a["s_mean"][0], 2))
        put(f"fp.{k}.sci", ci(a["s_mean"]))
        put(f"fp.{k}.c", num(a["c_mean"][0], 2))
        put(f"fp.{k}.greedyno", a["greedy"].get("NO", 0))
        put(f"fp.{k}.greedynone", a["greedy"].get("NONE", 0))
        put(f"fp.{k}.flipsraw", a["flips_raw"])
        put(f"fp.{k}.flipsnorm", a["flips_norm"])
        put(f"fp.{k}.gnonormyes", len(missed(recs)))
        put(f"fp.{k}.none", num(a["sampled"].get("NONE", 0.0), 2))
        put(f"fp.{k}.gapmin", num(min(r["gap"] for r in recs), 1))
        put(f"fp.{k}.based", num(a["first_token"].get("Based", 0.0), 2))
        put(f"fp.{k}.pyesbased", num(a["opening"].get("based", {}).get("p_yes", float("nan")),
                                     2))
        put(f"fp.{k}.terse", sum(r["greedy"].strip() == "Yes." for r in recs))
        if arm == "base":
            continue
        put(f"fp.{k}.dgap", num(a["gap_change_median"], 1, sign=True))
        put(f"fp.{k}.sdrop", num(a["s_drop"][0], 2))
        put(f"fp.{k}.sdropci", ci(a["s_drop"]))
        put(f"fp.{k}.cdropci", ci(a["c_drop"]))
        for rd in ("raw", "norm"):
            put(f"fp.{k}.{rd}drop", num(a[f"{rd}_drop"][0], 2))
            for tag in ("s", "c"):
                vs = a[f"{rd}_vs_{tag}"]
                sfx = "" if tag == "s" else "c"
                put(f"fp.{k}.{rd}vs{sfx}", ci(vs["diff"], sign=True))
                put(f"fp.{k}.{rd}vs{sfx}.v", verdict(vs["verdict"]))
        if arm in CLAMP_OPS:
            put(f"fp.{k}.e2rule", verdict(a["e2_rule"]))
    for g in ("fp_banked", "fp_fresh"):
        if g in S:
            gk = g.replace("_", "")
            for arm in CLAMP_OPS:
                k = ARMS[arm][0]
                put(f"{gk}.{k}.sdropci", ci(S[g][arm]["s_drop"]))
                put(f"{gk}.{k}.greedyno", S[g][arm]["greedy"].get("NO", 0))
                put(f"{gk}.{k}.e2rule", verdict(S[g][arm]["e2_rule"]))
            put(f"{gk}.base.s", num(S[g]["base"]["s_mean"][0], 2))
    clamp_pno = max(fp[a]["mass"] - fp[a]["raw"] for a in CLAMP_OPS)
    put("fp.clamp.pnomax", num(clamp_pno, 3))
    put("fp.clamp.gapmin", num(min(r["arms"][a]["gap"] for r in fp_rows for a in CLAMP_OPS), 1))
    put("fp.clamp.terse", sum(r["arms"][a]["greedy"].strip() == "Yes." for r in fp_rows
                              for a in CLAMP_OPS))
    put("fp.clamp.nfilmarms", len(fp_rows) * len(CLAMP_OPS))
    for arm in CLAMP_OPS:
        put(f"fp.{ARMS[arm][0]}.dgapabs", num(abs(fp[arm]["gap_change_median"]), 1))
    # occlusion as the reference: how far either readout strays from s, against P_norm's shortfall
    put("occ.maxdiff", num(max(abs(fp[a][f"{rd}_vs_s"]["diff"][0]) for a in OCC_ARMS
                               for rd in ("raw", "norm")), 2))
    put("fp.clamp.minshortfall", num(min(-fp[a]["norm_vs_s"]["diff"][0] for a in CLAMP_OPS), 2))
    occ_mis = {(a, rd) for a in OCC_ARMS for rd in ("raw", "norm")
               if fp[a][f"{rd}_vs_s"]["verdict"] == "MISREADS"}
    if occ_mis != {("black", "norm"), ("blur", "raw")} or any(
            fp[a][f"{rd}_vs_s"]["diff"][0] <= 0 for a, rd in occ_mis):
        warnings.append(f"occlusion MISREADS cells are {sorted(occ_mis)}; prose names black "
                        "P_norm and blur P_raw, both overshooting")
    # film by film (post hoc): of the films whose greedy answer is no, how many P_norm still calls yes
    for name, arms in (("clamp", CLAMP_OPS), ("occ", ("black", "mean", "blur"))):
        recs = [r["arms"][a] for r in fp_rows for a in arms]
        put(f"pf.{name}.gno", sum(x["greedy_parsed"] == "NO" for x in recs))
        put(f"pf.{name}.gnoyes", len(missed(recs)))
        # the counts are over (film, variant) pairs; also count the distinct films behind them
        put(f"pf.{name}.gnofilms", sum(any(r["arms"][a]["greedy_parsed"] == "NO" for a in arms)
                                       for r in fp_rows))
        put(f"pf.{name}.gnoyesfilms", sum(bool(missed([r["arms"][a] for a in arms]))
                                          for r in fp_rows))
    put("pf.clamp.missmin", num(min(x["norm"] for r in fp_rows for a in CLAMP_OPS
                                    for x in missed([r["arms"][a]])), 2))
    # last-layer features: edited at image positions, their output reaches no later token
    last = clt_layers() - 1
    n_last = [sum(lay == last for lay, _ in r["clamp_pairs"]) for r in fp_rows]
    put("clamp.nlast.mean", num(np.mean(n_last), 0))
    put("clamp.nlast.min", min(n_last))
    put("clamp.nlast.max", max(n_last))
    put("fp.scale1.rawvsthree", ci(fp["clamp_scale-1"]["raw_vs_s"]["diff"], 3, sign=True))
    put("fp.clamp.maxshortfall", num(max(-fp[a]["norm_vs_s"]["diff"][0] for a in CLAMP_OPS), 2))

    # verdicts
    for key in ("V1_raw_s", "V1_norm_s", "V1_raw_c", "V1_norm_c", "V3_s", "V3_c", "V2"):
        if key in V:
            put(f"v.{key.replace('_', '')}", verdict(V[key]))

    # routes table and numbers
    rt = {arm: routes([r["arms"][arm] for r in fp_rows]) for arm in ARMS}
    for arm, (k, _) in ARMS.items():
        for f in ("direct", "direct_yes", "reasoned", "r_yes", "r_no", "r_none"):
            put(f"route.{k}.{f.replace('_', '')}", num(rt[arm][f], 2))
        # share of all samples that reason first and conclude yes: what P_raw leaves out
        put(f"route.{k}.ryesall", num(rt[arm]["reasoned"] * rt[arm]["r_yes"], 2))
    lines = []
    for arm in ("base", *CLAMP_OPS, "black"):
        t = rt[arm]
        lines.append(f"{ARMS[arm][1]} & {t['direct']:.2f} & {t['direct_yes']:.2f} & "
                     f"{t['reasoned']:.2f} & {t['r_yes']:.2f} / {t['r_no']:.2f} / "
                     f"{t['r_none']:.2f} \\\\")
    table("routes", "\\begin{tabular}{lcccc}\n\\toprule\n"
          "& \\multicolumn{2}{c}{answers directly} & \\multicolumn{2}{c}{reasons first} \\\\\n"
          "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
          "Intervention & share & says yes & share & says yes / no / neither \\\\\n\\midrule\n"
          + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}")

    # main table: readouts and answers
    lines = []
    for arm, (_k, label) in ARMS.items():
        a = fp[arm]
        dg = "--" if arm == "base" else f"${a['gap_change_median']:+.1f}$"
        fl = f"{a['flips_raw']} / {a['flips_norm']}"
        nm = len(missed([r["arms"][arm] for r in fp_rows]))
        lines.append(f"{label} & {a['raw']:.3f} & {a['norm']:.3f} & {dg} & {fl} & "
                     f"{a['s_mean'][0]:.2f} & {a['greedy'].get('NO', 0)} ({nm}) \\\\")
        if arm == "clamp_scale-2":
            lines.append("\\midrule")
    table("main", "\\begin{tabular}{lcccccc}\n\\toprule\n"
          "& \\multicolumn{4}{c}{first token} & \\multicolumn{2}{c}{written answer} \\\\\n"
          "\\cmidrule(lr){2-5}\\cmidrule(lr){6-7}\n"
          "Intervention & $\\Praw$ & $\\Pnorm$ & median $\\Delta$ change & below $0.5$ "
          "& $s$ & greedy no \\\\\n"
          "& & & (nats) & ($\\Praw$ / $\\Pnorm$) & & ($\\Pnorm$ yes) \\\\\n\\midrule\n"
          + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}")

    # the pre-registered comparison: readout drop minus answer drop
    def cell(t: tuple, sign: bool = True, d: int = 2) -> str:
        f = f"+.{d}f" if sign else f".{d}f"
        z = "0." + "0" * d
        return (f"${t[0]:{f}}$ {{\\scriptsize[${t[1]:{f}}$,\\,${t[2]:{f}}$]}}"
                .replace(f"$-{z}$", f"${z}$").replace(f"$+{z}$", f"${z}$"))

    short = {"clamp_scale-1": "\\texttt{scale} $-1$", "clamp_ablate+0": "\\texttt{ablate}",
             "clamp_scale-2": "\\texttt{scale} $-2$", "black": "evidence, black",
             "mean": "evidence, mean", "blur": "evidence, blur", "border": "border, black"}
    lines = ["\\multicolumn{6}{l}{\\emph{Suppression}} \\\\"]
    for arm in short:
        label = "\\quad " + short[arm]
        a = fp[arm]
        if arm == "black":
            lines.append("\\multicolumn{6}{l}{\\emph{Occlusion (reference)}} \\\\")
        lines.append(f"{label} & {cell(a['s_drop'], False)} & {cell(a['raw_vs_s']['diff'])} & "
                     f"{verdict(a['raw_vs_s']['verdict'])} & {cell(a['norm_vs_s']['diff'])} & "
                     f"{verdict(a['norm_vs_s']['verdict'])} \\\\")
    table("v1", "\\begin{tabular}{lccccc}\n\\toprule\n"
          "& & \\multicolumn{2}{c}{$\\Praw$} & \\multicolumn{2}{c}{$\\Pnorm$} \\\\\n"
          "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\n"
          "Intervention & drop in $s$ & difference & verdict & difference & verdict "
          "\\\\\n\\midrule\n"
          + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}")

    # true positives
    lines = []
    for g, name in TP.items():
        if g not in S:
            continue
        a, b = S[g]["clamp_scale-1"], S[g]["base"]
        gk = g.replace("_", "")
        put(f"{gk}.base.s", num(b["s_mean"][0], 2))
        put(f"{gk}.base.raw", num(b["raw"], 2))
        put(f"{gk}.base.mass", num(b["mass"], 2))
        put(f"{gk}.scale1.sdropci", ci(a["s_drop"]))
        put(f"{gk}.scale1.sdrop", num(a["s_drop"][0], 2))
        put(f"{gk}.scale1.normvs.v", verdict(a["norm_vs_s"]["verdict"]))
        put(f"{gk}.scale1.rawvs.v", verdict(a["raw_vs_s"]["verdict"]))
        put(f"{gk}.black.sdropci", ci(S[g]["black"]["s_drop"]))
        put(f"{gk}.black.sdrop", num(S[g]["black"]["s_drop"][0], 2))
        lines.append(f"{name.capitalize()} & {b['raw']:.2f} & {b['mass']:.2f} & "
                     f"{b['s_mean'][0]:.2f} & {cell(a['s_drop'], False)} & "
                     f"{cell(a['raw_vs_s']['diff'])} & {cell(a['norm_vs_s']['diff'])} & "
                     f"{cell(S[g]['black']['s_drop'], False)} \\\\")
    if not lines:
        table("tp", "\\todo{true-positive groups not run yet}")
    else:
        table("tp", "\\begin{tabular}{lccccccc}\n\\toprule\n"
              "& \\multicolumn{3}{c}{no intervention} & \\multicolumn{3}{c}{suppression, "
              "\\texttt{scale} $-1$} & evidence black \\\\\n"
              "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-8}\n"
              "Finding & $\\Praw$ & $m$ & $s$ & drop in $s$ & difference, $\\Praw$ & "
              "difference, $\\Pnorm$ & drop in $s$ \\\\\n\\midrule\n"
              + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}")

    # the quoted example (first check's film, same feature set)
    ex = next((r for r in rows if r["image"] == "00000655_001.png"), None)
    if ex:
        put("ex.norm", num(ex["arms"]["clamp_scale-1"]["norm"], 3))
        put("ex.clamp", "\\texttt{" + tex_escape(ex["arms"]["clamp_scale-1"]["greedy"].strip())
            + "}")
        put("ex.base", "\\texttt{" + tex_escape(ex["arms"]["base"]["greedy"].strip()) + "}")

    # reproduction: E4's first 20 films against E2 (same films, feature sets and software)
    e2 = {r["image"]: r for r in json.loads((R / "readout_generation_check.json").read_text())
          ["rows"]}
    diffs = [abs(r["arms"][arm][q] - e2[r["image"]][arm][q])
             for r in rows if r["group"] == "fp_banked"
             for arm in ARMS for q in ("raw", "norm")]
    if diffs:
        put("repro.e4e2.maxdiff", num(max(diffs), 3))


